inline uint16_t KoreanToUnicode(uint16_t EUC_KR)
{
    uint8_t upper = (uint8_t)(EUC_KR >> 8);
    uint8_t lower = (uint8_t)(EUC_KR & 0xFF);

    for (const auto& entry : kKoreanToUnicode)
    {
        if (entry.UpperByte == upper && entry.LowerByte == lower)
            return entry.Unicode;
    }

    // Default: return ASCII range unchanged
    if (EUC_KR < 0x80) return EUC_KR;
    return 0xFFFD; // Unicode replacement character
}

inline std::string KoreanLocaleToUTF8(const std::string& KoreanLocale)
{
    std::string result;
    for (size_t i = 0; i < KoreanLocale.size(); ++i)
    {
        if (KoreanLocale[i] >= 0)
        {
            result += KoreanLocale[i];
        }
        else if (i + 1 < KoreanLocale.size())
        {
            uint16_t euc = ((uint8_t)KoreanLocale[i] << 8) | (uint8_t)KoreanLocale[i + 1];
            uint16_t unicode = KoreanToUnicode(euc);
            if (unicode < 0x80)
            {
                result += (char)unicode;
            }
            else if (unicode < 0x800)
            {
                result += (char)(0xC0 | (unicode >> 6));
                result += (char)(0x80 | (unicode & 0x3F));
            }
            else
            {
                result += (char)(0xE0 | (unicode >> 12));
                result += (char)(0x80 | ((unicode >> 6) & 0x3F));
                result += (char)(0x80 | (unicode & 0x3F));
            }
            ++i;
        }
    }
    return result;
}

